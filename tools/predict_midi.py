def show_processing_status(csv_file_path, output_midi_dir):
    """
    Show the current processing status
    """
    try:
        df = pd.read_csv(csv_file_path)
        filtered_df = df[df['split_encoded'] != 3]
        
        total_files = len(filtered_df)
        
        # Count actual MIDI files that exist
        midi_files_exist = 0
        for _, row in filtered_df.iterrows():
            midi_id = str(row['midi_id'])
            output_midi_filename = f"{midi_id}.mid"
            output_midi_path = os.path.join(output_midi_dir, output_midi_filename)
            if os.path.exists(output_midi_path):
                midi_files_exist += 1
        
        print(f"\n📊 Processing Status Report:")
        print(f"   Total files to process: {total_files}")
        print(f"   MIDI files that exist: {midi_files_exist}")
        print(f"   Files still to process: {total_files - midi_files_exist}")
        
        return total_files - midi_files_exist
        
    except Exception as e:
        print(f"Error checking status: {e}")
        return -1

