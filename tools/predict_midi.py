import pandas as pd
import os
import subprocess
import sys
from pathlib import Path

def process_audio_with_transkun(csv_file_path, output_midi_dir, audio_home_dir, transkun_command_template="transkun {input_audio} {output_midi}", skip_existing=True, timeout_minutes=15):
    """
    Process CSV file to convert audio files to MIDI using Transkun for split_encoded != 2
    
    Args:
        csv_file_path (str): Path to the input CSV file
        output_midi_dir (str): Directory to store generated MIDI files
        audio_home_dir (str): Home directory where audio files are located
        transkun_command_template (str): Template for the transkun command
        skip_existing (bool): If True, skip files that already have MIDI output
        timeout_minutes (int): Timeout in minutes for each file processing
    """
    
    # Create output directory if it doesn't exist
    os.makedirs(output_midi_dir, exist_ok=True)
    
    # Read the CSV file
    try:
        df = pd.read_csv(csv_file_path)
        print(f"Loaded CSV with {len(df)} rows")
    except Exception as e:
        print(f"Error reading CSV file: {e}")
        return
    
    # Check if required columns exist
    required_columns = ['orig_audio_filename', 'midi_id', 'split_encoded']
    missing_columns = [col for col in required_columns if col not in df.columns]
    if missing_columns:
        print(f"Error: Missing required columns: {missing_columns}")
        return
    
    # Filter rows where split_encoded != 2
    filtered_df = df[df['split_encoded'] != 2].copy()
    print(f"Found {len(filtered_df)} rows with split_encoded != 2")
    
    if len(filtered_df) == 0:
        print("No rows to process")
        return
    
    # Initialize the new column if it doesn't exist
    if 'transkun_filename' not in filtered_df.columns:
        filtered_df['transkun_filename'] = ''
    
    # Process each row
    processed_count = 0
    failed_count = 0
    skipped_count = 0
    
    for idx, row in filtered_df.iterrows():
        try:
            # Get the audio file path and midi_id
            audio_filename = row['orig_audio_filename']
            midi_id = str(row['midi_id'])
            
            # Create output MIDI filename
            output_midi_filename = f"{midi_id}.mid"
            output_midi_path = os.path.join(output_midi_dir, output_midi_filename)
            
            # Skip if MIDI file already exists and skip_existing is True
            if skip_existing and os.path.exists(output_midi_path):
                # Update the CSV record for consistency
                filtered_df.at[idx, 'transkun_filename'] = output_midi_filename
                print(f"⏭️  Skipping existing file: {output_midi_filename}")
                skipped_count += 1
                continue
            
            # Construct full path to audio file using home directory
            audio_file_path = os.path.join(audio_home_dir, audio_filename)
            
            # Check if audio file exists
            if not os.path.exists(audio_file_path):
                print(f"⚠️  Warning: Audio file not found: {audio_file_path}")
                failed_count += 1
                continue
            
            # Prepare the transkun command
            command = transkun_command_template.format(
                input_audio=audio_file_path,
                output_midi=output_midi_path
            )
            
            print(f"🎵 Processing {audio_filename} -> {output_midi_filename}")
            print(f"   Running command: {command}")
            
            # Run the transkun command
            result = subprocess.run(
                command,
                shell=True,
                capture_output=True,
                text=True,
                timeout=timeout_minutes * 60  # Convert minutes to seconds
            )
            
            if result.returncode == 0:
                # Success - update the dataframe
                filtered_df.at[idx, 'transkun_filename'] = output_midi_filename
                processed_count += 1
                print(f"✅ Successfully processed: {output_midi_filename}")
            else:
                print(f"❌ Error processing {audio_filename}:")
                print(f"   Return code: {result.returncode}")
                print(f"   Stderr: {result.stderr}")
                failed_count += 1
                
        except subprocess.TimeoutExpired:
            print(f"⏰ Timeout ({timeout_minutes} min) processing {audio_filename}")
            print(f"   Consider increasing timeout or checking if this file is problematic")
            failed_count += 1
        except Exception as e:
            print(f"❌ Error processing {audio_filename}: {e}")
            failed_count += 1
    
    # Save the processed CSV
    output_csv_path = csv_file_path.replace('.csv', '_processed.csv')
    try:
        # Save only the processed rows back to the original dataframe structure
        # We need to update the original dataframe with our changes
        df.loc[filtered_df.index, 'transkun_filename'] = filtered_df['transkun_filename']
        df.to_csv(output_csv_path, index=False)
        
        print(f"\n📄 Saved processed CSV to: {output_csv_path}")
        print(f"✅ Successfully processed: {processed_count} files")
        print(f"⏭️  Skipped existing: {skipped_count} files")
        print(f"❌ Failed to process: {failed_count} files")
        print(f"📊 Total in filtered set: {len(filtered_df)} files")
        
    except Exception as e:
        print(f"Error saving processed CSV: {e}")

